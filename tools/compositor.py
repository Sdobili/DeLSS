"""Generate compositor-native screen shaders from the same DeLSS sources.

On Wayland a client cannot capture the whole screen or stack a window over
everything, so delss-overlay's X11 path does not apply. Compositors that run
a user shader over the final frame can host DeLSS directly instead. This
flattens a preset's multi-pass chain into ONE fragment shader:

* every pass becomes a function ``vec4 passN(vec2 uv)``; a pass that samples
  ``src(p)`` calls the previous pass at ``p`` (recomputed per tap: correct but
  costlier than real multi-pass, see README);
* artist parameters are baked in as constants from the preset;
* there is no history, motion or G-buffer, so ``temporal`` is dropped and
  every pass takes its colour-only fallback, as in delss-overlay.

Outputs ``compositor/hyprland/delss-<preset>.frag`` (Hyprland
``decoration:screen_shader``). ``--check`` fails if they are stale; the
compositor shader test renders them and compares with the WebGL goldens.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "compositor" / "hyprland"
DROPPED = {"temporal"}  # needs the previous frame, which screen shaders do not get

PRELUDE_DROP = re.compile(
    r"^(in vec2 vUv;|out vec4 fragColor;|uniform .*;.*|precision .*;|vec4 src\(vec2 uv\).*)$",
    re.MULTILINE,
)
DELSS_OUT = re.compile(r"vec4 delssOut\(vec3 styled\) \{.*?\n\}\n", re.DOTALL)


def glsl_float(v: float) -> str:
    s = repr(float(v))
    return s if ("." in s or "e" in s) else s + ".0"


def const_for(name: str, ptype: str, desc: dict[str, Any], value: Any, palettes: dict[str, Any]) -> str:
    if ptype == "float":
        return f"const float {name} = {glsl_float(value)};"
    if ptype == "int":
        return f"const int {name} = {int(value)};"
    if ptype == "color":
        rgb = gen.hex_to_rgb(value)
        return f"const vec3 {name} = vec3({', '.join(glsl_float(c) for c in rgb)});"
    # palette: 16-entry array + size
    colors = [] if value == "none" else palettes[value]["rgb"]
    padded = colors + [[0.0, 0.0, 0.0]] * (16 - len(colors))
    items = ", ".join(f"vec3({', '.join(glsl_float(c) for c in rgb)})" for rgb in padded)
    return f"const vec3 {name}[16] = vec3[16]({items});\nconst int {name}Size = {len(colors)};"


def flatten_pass(index: int, name: str, params: dict[str, Any], data: dict[str, Any]) -> str:
    body = (gen.SHADERS / "passes" / f"{name}.frag").read_text()
    manifest = data["manifest"][name]["params"]
    prefix = f"u{index}_"
    consts = []
    for pname, desc in manifest.items():
        value = params.get(pname, desc["default"])
        consts.append(const_for(prefix + pname, desc["type"], desc, value, data["palettes"]))
    body = re.sub(r"^\s*uniform\s+[^;]+;.*$", "", body, flags=re.MULTILINE)
    body = re.sub(r"\bu_(\w+)", lambda m: prefix + m.group(1), body)
    prev = f"pass{index - 1}" if index > 0 else "screen"
    body = re.sub(r"\bsrc\(", f"{prev}(", body)
    body = body.replace("gl_FragCoord", "delss_fc").replace("vUv", "delss_uv")
    body = re.sub(r"fragColor\s*=\s*(.*?);\s*return;", r"return \1;", body, flags=re.DOTALL)
    body = re.sub(r"fragColor\s*=\s*(.*?);", r"return \1;", body, flags=re.DOTALL)
    body = re.sub(r"\bdelssOut\(", "delssOutFull(", body)
    body = body.replace(
        "void main() {",
        f"vec4 pass{index}(vec2 delss_uv) {{\n  vec4 delss_fc = vec4(delss_uv * uResolution, 0.0, 1.0);",
    )
    return f"// ---- pass {index}: {name}\n" + "\n".join(consts) + "\n" + body


def flatten(preset: dict[str, Any], data: dict[str, Any]) -> tuple[str, int]:
    common = (gen.SHADERS / "common.glsl").read_text()
    common = DELSS_OUT.sub("", common)
    common = PRELUDE_DROP.sub("", common)
    steps = [s for s in preset["passes"] if s["pass"] not in DROPPED]
    passes = [flatten_pass(i, s["pass"], s.get("params", {}), data) for i, s in enumerate(steps)]
    head = f"""#version 300 es
// DeLSS preset "{preset["id"]}" ({preset["label"]}) as one Hyprland screen shader.
// Generated by tools/compositor.py from shaders/. Do not edit by hand.
// Usage (hyprland.conf):  decoration:screen_shader = /path/to/this/file
// Colour only, no temporal pass; passes run at full effect (intensity 1).
precision highp float;
precision highp int;

in vec2 v_texcoord;
uniform sampler2D tex;
out vec4 fragColor;

// Host-provided values in the DeLSS contract, fixed for a screen shader.
vec2 uResolution;
const int uFrame = 0;
const bool uHasDepth = false;
const bool uHasNormal = false;
const bool uHasMotion = false;
const bool uHasHistory = false;
uniform sampler2D uDepth;   // never sampled: uHasDepth is false
uniform sampler2D uNormal;  // never sampled: uHasNormal is false

vec4 screen(vec2 uv) {{ return vec4(texture(tex, uv).rgb, 1.0); }}
vec4 delssOutFull(vec3 styled) {{ return vec4(styled, 1.0); }}
"""
    tail = f"""
void main() {{
  uResolution = vec2(textureSize(tex, 0));
  fragColor = pass{len(steps) - 1}(v_texcoord);
}}
"""
    text = head + common + "\n" + "\n".join(passes) + tail
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text, len(steps)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    args = parser.parse_args()
    data = gen.load()
    stale = []
    OUT.mkdir(parents=True, exist_ok=True)
    for preset in data["presets"]:
        text, _ = flatten(preset, data)
        path = OUT / f"delss-{preset['id']}.frag"
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.name)
        else:
            path.write_text(text)
    if stale:
        print("stale compositor shaders (run tools/compositor.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
