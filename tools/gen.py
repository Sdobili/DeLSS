#!/usr/bin/env python3
"""Generate the WebGL and C++ bindings from the single shader source of truth.

Inputs (all under shaders/):
  fullscreen.vert, common.glsl, passes/*.frag, passes.json, palettes.json, presets.json
Outputs:
  web/src/generated.js            ES module consumed by the WebGL2 runtime
  cpp/include/delss/generated.hpp header consumed by the C++ GLES3 library

The script also validates the contract between the manifest and the shaders:
every declared parameter must have a matching uniform and vice versa, and
every preset may only reference known passes, parameters and palettes.

Usage: tools/gen.py           write outputs
       tools/gen.py --check   fail if outputs are stale (used by CI)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ROOT / "shaders"
WEB_OUT = ROOT / "web" / "src" / "generated.js"
CPP_OUT = ROOT / "cpp" / "include" / "delss" / "generated.hpp"
HEADER = "Generated by tools/gen.py from shaders/. Do not edit by hand."
UNIFORM_RE = re.compile(r"^\s*uniform\s+\w+\s+(u_\w+)", re.MULTILINE)


class ManifestError(Exception):
    pass


def hex_to_rgb(value: str) -> list[float]:
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        raise ManifestError(f"bad color {value!r}, expected #rrggbb")
    return [round(int(value[i : i + 2], 16) / 255.0, 6) for i in (1, 3, 5)]


def expected_uniforms(params: dict[str, Any]) -> set[str]:
    names: set[str] = set()
    for name, desc in params.items():
        names.add(f"u_{name}")
        if desc["type"] == "palette":
            names.add(f"u_{name}Size")
    return names


def load() -> dict[str, Any]:
    common = (SHADERS / "common.glsl").read_text()
    vertex = (SHADERS / "fullscreen.vert").read_text()
    manifest = json.loads((SHADERS / "passes.json").read_text())
    palettes = json.loads((SHADERS / "palettes.json").read_text())
    presets = json.loads((SHADERS / "presets.json").read_text())

    files = {p.stem for p in (SHADERS / "passes").glob("*.frag")}
    if files != set(manifest):
        raise ManifestError(f"passes/*.frag {sorted(files)} != passes.json {sorted(manifest)}")

    passes: dict[str, str] = {}
    for name in sorted(manifest):
        body = (SHADERS / "passes" / f"{name}.frag").read_text()
        declared = set(UNIFORM_RE.findall(body))
        expected = expected_uniforms(manifest[name]["params"])
        if declared != expected:
            raise ManifestError(
                f"{name}: uniforms {sorted(declared)} do not match manifest {sorted(expected)}"
            )
        passes[name] = f"#version 300 es\n// DeLSS pass: {name}\n{common}\n{body}"

    for pal in palettes.values():
        if not 1 <= len(pal["colors"]) <= 16:
            raise ManifestError("palettes hold 1..16 colors")
        pal["rgb"] = [hex_to_rgb(c) for c in pal["colors"]]

    for pdesc in manifest.values():
        for name, desc in pdesc["params"].items():
            if desc["type"] == "color":
                desc["rgb"] = hex_to_rgb(desc["default"])
            elif desc["type"] == "palette" and desc["default"] not in [*palettes, "none"]:
                raise ManifestError(f"unknown default palette for {name}")

    ids: set[str] = set()
    for preset in presets:
        if preset["id"] in ids:
            raise ManifestError(f"duplicate preset {preset['id']}")
        ids.add(preset["id"])
        for step in preset["passes"]:
            if step["pass"] not in manifest:
                raise ManifestError(f"{preset['id']}: unknown pass {step['pass']}")
            step.setdefault("params", {})
            known = manifest[step["pass"]]["params"]
            for key, value in step["params"].items():
                if key not in known:
                    raise ManifestError(f"{preset['id']}: {step['pass']} has no param {key}")
                if known[key]["type"] == "palette" and value not in [*palettes, "none"]:
                    raise ManifestError(f"{preset['id']}: unknown palette {value}")

    return {
        "vertex": vertex,
        "passes": passes,
        "manifest": manifest,
        "palettes": palettes,
        "presets": presets,
    }


def emit_js(data: dict[str, Any]) -> str:
    def dump(obj: Any) -> str:
        return json.dumps(obj, indent=2, ensure_ascii=False)

    return (
        f"// {HEADER}\n"
        f"export const VERTEX_SHADER = {dump(data['vertex'])};\n\n"
        f"export const PASS_SHADERS = {dump(data['passes'])};\n\n"
        f"export const PASSES = {dump(data['manifest'])};\n\n"
        f"export const PALETTES = {dump(data['palettes'])};\n\n"
        f"export const PRESETS = {dump(data['presets'])};\n"
    )


def cpp_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def cpp_floats(values: list[float]) -> str:
    return "{" + ", ".join(f"{v:.6g}f" for v in values) + "}"


def cpp_value(desc: dict[str, Any], value: Any) -> str:
    kind = desc["type"]
    if kind == "color":
        return f"ParamValue::color({cpp_floats(hex_to_rgb(value))})"
    if kind == "palette":
        return f"ParamValue::palette({cpp_str(value)})"
    return f"ParamValue::number({float(value):.6g}f)"


def emit_cpp(data: dict[str, Any]) -> str:
    out = [
        f"// {HEADER}",
        "// NOLINTBEGIN",
        "#pragma once",
        "",
        "#include <array>",
        "#include <string_view>",
        "#include <vector>",
        "",
        '#include "delss/types.hpp"',
        "",
        "namespace delss::generated {",
        "",
        f'inline constexpr std::string_view kVertexShader = R"delss({data["vertex"]})delss";',
        "",
    ]
    for name, src in data["passes"].items():
        out.append(f'inline constexpr std::string_view k{name.capitalize()}Shader = R"delss({src})delss";')
        out.append("")

    out.append("inline std::vector<PassInfo> passes() {")
    out.append("  return {")
    for name, pdesc in data["manifest"].items():
        params = []
        for pname, d in pdesc["params"].items():
            lo, hi = float(d.get("min", 0)), float(d.get("max", 0))
            params.append(
                f"{{{cpp_str(pname)}, ParamType::{d['type'].capitalize()}, "
                f"{cpp_value(d, d['default'])}, {lo:.6g}f, {hi:.6g}f}}"
            )
        out.append(
            f"    {{{cpp_str(name)}, {cpp_str(pdesc['label'])}, k{name.capitalize()}Shader, "
            f"{{{', '.join(params)}}}}},"
        )
    out.append("  };")
    out.append("}")
    out.append("")

    out.append("inline std::vector<PaletteInfo> palettes() {")
    out.append("  return {")
    for name, pal in data["palettes"].items():
        cols = ", ".join(cpp_floats(c) for c in pal["rgb"])
        out.append(f"    {{{cpp_str(name)}, {cpp_str(pal['label'])}, {{{cols}}}}},")
    out.append("  };")
    out.append("}")
    out.append("")

    out.append("inline std::vector<Preset> presets() {")
    out.append("  return {")
    for preset in data["presets"]:
        steps = []
        for step in preset["passes"]:
            known = data["manifest"][step["pass"]]["params"]
            overrides = ", ".join(
                f"{{{cpp_str(k)}, {cpp_value(known[k], v)}}}" for k, v in step["params"].items()
            )
            steps.append(f"{{{cpp_str(step['pass'])}, {{{overrides}}}}}")
        out.append(f"    {{{cpp_str(preset['id'])}, {cpp_str(preset['label'])}, {{{', '.join(steps)}}}}},")
    out.append("  };")
    out.append("}")
    out.append("")
    out.append("}  // namespace delss::generated")
    out.append("// NOLINTEND")
    return "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    try:
        data = load()
    except ManifestError as err:
        print(f"gen.py: {err}", file=sys.stderr)
        return 1
    targets = {WEB_OUT: emit_js(data)}
    if (ROOT / "cpp" / "CMakeLists.txt").exists():
        targets[CPP_OUT] = emit_cpp(data)
    stale = []
    for path, text in targets.items():
        if path.exists() and path.read_text() == text:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print(f"gen.py: stale outputs {stale}; run tools/gen.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
